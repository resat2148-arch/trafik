export type StrKey = keyof typeof STR;

let lang: Lang = 'en';

export function detectLang(): Lang {
  try {
    const n = (navigator.language || 'en').toLowerCase();
    return n.startsWith('tr') ? 'tr' : 'en';
  } catch {
    return 'en';
  }
}

export function setLang(l: Lang): void {
  lang = l;
  document.documentElement.lang = l;
}

export function getLang(): Lang {
  return lang;
}

export function t(key: StrKey, vars?: Record<string, string | number>): string {
  const e = STR[key];
  let s: string = e ? e[lang] ?? e.en : key;
  if (vars) for (const k of Object.keys(vars)) s = s.split(`{${k}}`).join(String(vars[k]));
  return s;
}

export function money(n: number): string {
  const neg = n < 0;
  const v = Math.abs(Math.round(n));
  const s = v >= 1e6 ? `${(v / 1e6).toFixed(1)}M` : v >= 10000 ? `${(v / 1000).toFixed(1)}k` : v.toLocaleString('en-US');
  return `${neg ? '-' : ''}$${s}`;
}
